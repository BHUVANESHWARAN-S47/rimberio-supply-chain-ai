from typing import List, Optional, Dict, Any
from enum import Enum
from pydantic import BaseModel, Field, field_validator, model_validator
from backend.app.schemas.common import NegotiationAction

class ConcessionStrategy(str, Enum):
    BOULWARE = "BOULWARE"      # Firm, makes concessions late near deadline (beta > 1)
    CONCEDER = "CONCEDER"      # Yields early to secure volume (beta < 1)
    LINEAR = "LINEAR"          # Steady step-by-step concession (beta = 1)
    TIT_FOR_TAT = "TIT_FOR_TAT"# Matches buyer concession magnitude

class SupplierProfile(BaseModel):
    """Encapsulates a supplier's internal cost structure, constraints, and negotiation policy."""
    supplier_id: str
    supplier_code: str
    company_name: str
    product_id: str
    cogs: float = Field(gt=0, description="Cost of goods sold (baseline unit cost)")
    min_margin_pct: float = Field(default=0.15, ge=0.0, le=1.0, description="Minimum acceptable margin (reservation floor)")
    target_margin_pct: float = Field(default=0.35, ge=0.0, le=2.0, description="Target margin for initial quotation")
    min_order_quantity: int = Field(default=100, gt=0, description="Minimum Order Quantity (MOQ)")
    max_capacity: int = Field(default=100000, gt=0, description="Maximum batch production capacity")
    baseline_lead_time_days: int = Field(default=14, gt=0, description="Standard production and shipping lead time")
    min_lead_time_days: int = Field(default=7, gt=0, description="Fastest possible expedited lead time")
    acceptable_payment_terms: List[str] = Field(default_factory=lambda: ["Net 30", "Net 45"])
    concession_strategy: ConcessionStrategy = Field(default=ConcessionStrategy.BOULWARE)
    strategy_beta: float = Field(default=2.0, gt=0.0, description="Boulware beta parameter")

    @model_validator(mode="after")
    def validate_margins_and_lead_times(self) -> "SupplierProfile":
        if self.min_margin_pct > self.target_margin_pct:
            raise ValueError(f"min_margin_pct ({self.min_margin_pct}) cannot exceed target_margin_pct ({self.target_margin_pct})")
        if self.min_lead_time_days > self.baseline_lead_time_days:
            raise ValueError(f"min_lead_time_days ({self.min_lead_time_days}) cannot exceed baseline_lead_time_days ({self.baseline_lead_time_days})")
        return self

    @property
    def reservation_price(self) -> float:
        """Absolute floor price below which supplier will never transact."""
        return round(self.cogs * (1.0 + self.min_margin_pct), 2)

    @property
    def target_price(self) -> float:
        """Optimal target price for opening quotation."""
        return round(self.cogs * (1.0 + self.target_margin_pct), 2)

class BuyerOffer(BaseModel):
    """The incoming proposal or counteroffer received from the buyer organization."""
    offered_unit_price: float = Field(ge=0.0, description="Unit price offered by buyer")
    quantity_demanded: int = Field(gt=0, description="Quantity demanded by buyer")
    requested_delivery_days: int = Field(gt=0, description="Delivery lead time requested in days")
    payment_terms: str = Field(default="Net 30", description="Payment terms requested by buyer")
    buyer_notes: Optional[str] = Field(default=None, description="Optional text memorandum or notes")

class SupplierAgentInput(BaseModel):
    """Input payload provided to the SupplierAgent."""
    supplier_id: str
    product_id: str
    buyer_offer: BuyerOffer
    negotiation_round: int = Field(default=1, ge=1, description="Current negotiation round (1-indexed)")
    max_rounds: int = Field(default=5, ge=1, description="Maximum bargaining rounds allowed")
    profile_override: Optional[SupplierProfile] = Field(default=None, description="Optional explicit profile")

class SupplierQuotationResult(BaseModel):
    """Deterministic structured output generated by SupplierAgent."""
    supplier_id: str
    supplier_code: str
    company_name: str
    product_id: str
    action: NegotiationAction
    quoted_unit_price: float
    quoted_quantity: int
    quoted_delivery_days: int
    quoted_payment_terms: str
    margin_pct: float
    reservation_price: float
    target_price: float
    concession_rate: float
    constraint_violations: List[str] = Field(default_factory=list)
    reasoning: str
    adversarial_flags: List[str] = Field(default_factory=list)
